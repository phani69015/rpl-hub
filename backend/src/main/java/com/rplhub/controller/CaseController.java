package com.rplhub.controller;

import com.rplhub.model.AppUser;
import com.rplhub.model.CaseRow;
import com.rplhub.model.CaseView;
import com.rplhub.model.Declaration;
import com.rplhub.model.DecisionRequest;
import com.rplhub.model.EvidenceRequestBody;
import com.rplhub.model.ScoreRequest;
import com.rplhub.model.SubmitRequest;
import com.rplhub.service.AssessmentService;
import com.rplhub.service.CaseService;
import com.rplhub.service.EvidenceService;
import com.rplhub.service.ReportService;
import jakarta.validation.Valid;
import java.io.IOException;
import java.util.List;
import java.util.UUID;
import org.springframework.core.io.Resource;
import org.springframework.http.ContentDisposition;
import org.springframework.http.HttpHeaders;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.security.core.annotation.AuthenticationPrincipal;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.PutMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;
import org.springframework.web.multipart.MultipartFile;

/** Case endpoints for all roles; each service call enforces ownership/assignment. */
@RestController
@RequestMapping("/api/cases")
class CaseController {

    private static final String NO_SNIFF = "X-Content-Type-Options";

    private final CaseService cases;
    private final AssessmentService assessments;
    private final EvidenceService evidence;
    private final ReportService reports;

    CaseController(CaseService cases, AssessmentService assessments, EvidenceService evidence, ReportService reports) {
        this.cases = cases;
        this.assessments = assessments;
        this.evidence = evidence;
        this.reports = reports;
    }

    @GetMapping
    List<CaseRow> list(@AuthenticationPrincipal AppUser u) {
        return cases.list(u);
    }

    @GetMapping("/{id}")
    CaseView get(@AuthenticationPrincipal AppUser u, @PathVariable UUID id) {
        return cases.get(u, id);
    }

    /** Create-or-update a draft (and optionally submit). The id is generated by the client. */
    @PutMapping("/{id}")
    CaseView save(@AuthenticationPrincipal AppUser u, @PathVariable UUID id, @Valid @RequestBody Declaration d) {
        return cases.save(u, id, d);
    }

    @PutMapping("/{id}/evidence/{evidenceId}")
    CaseView addEvidence(@AuthenticationPrincipal AppUser u, @PathVariable UUID id, @PathVariable UUID evidenceId,
                         @RequestParam("file") MultipartFile file, @RequestParam(required = false) UUID competencyId,
                         @RequestParam(required = false) String note) throws IOException {
        return evidence.add(u, id, evidenceId, competencyId, note, file);
    }

    @GetMapping("/{id}/evidence/{evidenceId}/file")
    ResponseEntity<Resource> file(@AuthenticationPrincipal AppUser u, @PathVariable UUID id, @PathVariable UUID evidenceId) {
        var d = evidence.download(u, id, evidenceId);
        return ResponseEntity.ok()
            .header(HttpHeaders.CONTENT_DISPOSITION, ContentDisposition.attachment().filename(d.filename()).build().toString())
            .header(NO_SNIFF, "nosniff")
            .contentType(MediaType.parseMediaType(d.contentType()))
            .body(d.file());
    }

    @PostMapping("/{id}/evidence/submit")
    CaseView submitEvidence(@AuthenticationPrincipal AppUser u, @PathVariable UUID id) {
        return evidence.fulfil(u, id);
    }

    @PutMapping("/{id}/scores/{competencyId}")
    CaseView score(@AuthenticationPrincipal AppUser u, @PathVariable UUID id, @PathVariable UUID competencyId, @Valid @RequestBody ScoreRequest r) {
        return assessments.score(u, id, competencyId, r);
    }

    @PostMapping("/{id}/request-evidence")
    CaseView requestEvidence(@AuthenticationPrincipal AppUser u, @PathVariable UUID id, @Valid @RequestBody EvidenceRequestBody b) {
        return assessments.requestEvidence(u, id, b);
    }

    @PostMapping("/{id}/submit")
    CaseView submit(@AuthenticationPrincipal AppUser u, @PathVariable UUID id, @Valid @RequestBody SubmitRequest r) {
        return assessments.submit(u, id, r);
    }

    @PostMapping("/{id}/decision")
    CaseView decide(@AuthenticationPrincipal AppUser u, @PathVariable UUID id, @Valid @RequestBody DecisionRequest r) {
        return assessments.decide(u, id, r);
    }

    @GetMapping(value = "/{id}/report", produces = MediaType.TEXT_HTML_VALUE)
    ResponseEntity<String> reportHtml(@AuthenticationPrincipal AppUser u, @PathVariable UUID id) {
        return ResponseEntity.ok().header(NO_SNIFF, "nosniff").body(reports.html(cases.reportView(u, id)));
    }

    @GetMapping(value = "/{id}/report", params = "format=pdf", produces = MediaType.APPLICATION_PDF_VALUE)
    ResponseEntity<byte[]> reportPdf(@AuthenticationPrincipal AppUser u, @PathVariable UUID id) {
        CaseView view = cases.reportView(u, id);
        return ResponseEntity.ok()
            .header(HttpHeaders.CONTENT_DISPOSITION, ContentDisposition.inline().filename(view.caseNumber() + ".pdf").build().toString())
            .body(reports.pdf(view));
    }
}
