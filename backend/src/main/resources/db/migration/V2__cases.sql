create table assessor_trade (
    user_id text not null references app_user(id),
    trade text not null,
    primary key (user_id, trade)
);

create table worker_profile (
    user_id text primary key references app_user(id),
    full_name text not null,
    primary_trade text,
    years_experience integer check (years_experience between 0 and 60),
    skills text,
    updated_at text not null default (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);

-- Replaces the Postgres sequence for case numbers; incremented inside the creating transaction.
create table case_counter (
    id integer primary key check (id = 1),
    value integer not null
);
insert into case_counter(id, value) values (1, 0);

-- id is generated by the client so offline creation and repeated sync are idempotent.
create table rpl_case (
    id text primary key,
    case_number text not null unique,
    worker_id text not null references app_user(id),
    trade text not null,
    experience_years integer not null check (experience_years between 0 and 60),
    skills text not null,
    details text,
    status text not null check (status in ('DRAFT','NEW','AWAITING_QUALIFICATION','AWAITING_ASSESSOR',
        'IN_ASSESSMENT','EVIDENCE_REQUESTED','REPORT_PENDING','AWAITING_DECISION','DECIDED')),
    version integer not null default 1,
    qualification_version_id text references qualification_version(id),
    qualification_confirmed_by text references app_user(id),
    qualification_confirmed_at text,
    assessor_id text references app_user(id),
    assigned_by text references app_user(id),
    assigned_at text,
    created_at text not null default (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
    updated_at text not null default (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
    submitted_at text
);
create index idx_rpl_case_worker on rpl_case(worker_id);
create index idx_rpl_case_assessor on rpl_case(assessor_id);

create table match_suggestion (
    id text primary key,
    case_id text not null references rpl_case(id),
    qualification_version_id text not null references qualification_version(id),
    confidence real not null check (confidence between 0 and 1),
    explanation text not null,
    flagged integer not null,
    source text not null check (source in ('AI','KEYWORD')),
    created_at text not null default (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);
create index idx_match_suggestion_case on match_suggestion(case_id);

create table competency_score (
    case_id text not null references rpl_case(id),
    competency_id text not null references competency(id),
    score integer not null check (score >= 0),
    comment text,
    updated_by text not null references app_user(id),
    updated_at text not null default (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
    primary key (case_id, competency_id)
);

create table evidence (
    id text primary key,
    case_id text not null references rpl_case(id),
    competency_id text references competency(id),
    uploaded_by text not null references app_user(id),
    filename text not null,
    content_type text not null,
    size_bytes integer not null,
    note text,
    created_at text not null default (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);
create index idx_evidence_case on evidence(case_id);

create table evidence_request (
    id text primary key,
    case_id text not null references rpl_case(id),
    message text not null,
    requested_by text not null references app_user(id),
    created_at text not null default (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
    fulfilled_at text
);
create index idx_evidence_request_case on evidence_request(case_id);

create table assessment_submission (
    case_id text primary key references rpl_case(id),
    recommendation text not null check (recommendation in ('COMPETENT','NOT_YET_COMPETENT')),
    notes text,
    submitted_by text not null references app_user(id),
    submitted_at text not null default (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
    ai_summary text,
    ai_generated_at text
);

create table final_decision (
    case_id text primary key references rpl_case(id),
    outcome text not null check (outcome in ('COMPETENT','NOT_YET_COMPETENT')),
    rationale text,
    decided_by text not null references app_user(id),
    decided_at text not null default (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);
